/* Фудкост: расчёт. ЯВНО ТЕСТОВЫЕ данные «ТЕСТ …»; контрольные значения посчитаны вручную (см. комментарии) */
const { chromium } = require(process.env.PW_MODULE || 'playwright');
const path = require('path'), assert = require('assert');
const SRC = process.argv[2] || 'out/КБЖУ_калькулятор_автономный.html';
const errs = [];
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM || undefined, args: ['--no-sandbox'] });
  const page = await (await browser.newContext({ viewport: { width: 1300, height: 1100 } })).newPage();
  page.on('pageerror', e => errs.push('pageerror: ' + e.message));
  await page.route(/fonts\.(googleapis|gstatic)\.com/, r => r.abort());
  await page.goto('file://' + path.resolve(SRC));
  await page.evaluate(() => { localStorage.clear(); localStorage.setItem('kbzhu:tab', 'fc'); });
  await page.reload(); await page.waitForSelector('#fcObj');
  const res = await page.evaluate(() => {
    const F = window.kbzhuFc, S = F.S, O = 'oTEST', FROM = '2026-10-01', TO = '2026-10-31';
    S.ings.tMeat = { id: 'tMeat', name: 'ТЕСТ Мясо', price: 400 };
    S.ings.tCarr = { id: 'tCarr', name: 'ТЕСТ Морковь', price: 40 };
    S.recipes.tRagu = { name: 'ТЕСТ Рагу', output: 250, rows: [{ rid: 'a', ing: 'tMeat', net: 100, gross: 120, share: 100 }, { rid: 'b', ing: 'tCarr', net: 70, gross: 80, share: 100 }], ref: {}, ttk: {}, op: {} };
    const ops = (t) => S.fc.ops[t] = S.fc.ops[t] || {};
    let n = 0; const add = (t, o) => { o.obj = O; o.id = 'x' + (++n); o.b = o.b || 'b' + t; ops(t)[o.id] = o; };
    S.fc.batches.bmoves = { id: 'bmoves', type: 'moves', obj: O, objName: 'ТЕСТ', from: FROM, to: TO, file: 'ТЕСТ', map: { open: 3, tin: 4, tout: 5, ret: 6, close: 7 } };
    add('receipts', { d: '2026-10-05', doc: 'T1', sup: 'ТЕСТ А', nm: 'ТЕСТ Мясо', u: 'кг', q: 20, s: 8400 });
    add('receipts', { d: '2026-10-06', doc: 'T2', sup: 'ТЕСТ Б', nm: 'ТЕСТ Морковь', u: 'кг', q: 10, s: 450 });
    add('receipts', { d: '2026-10-07', doc: 'T3', sup: 'ТЕСТ Б', nm: 'ТЕСТ Неизвестное', u: 'кг', q: 3, s: 99 });
    add('moves', { nm: 'ТЕСТ Мясо', u: 'кг', open: 5, 'in': 20, out: 17, close: 8, b: 'bmoves' });
    add('moves', { nm: 'ТЕСТ Морковь', u: 'кг', open: 2, 'in': 10, close: 3, b: 'bmoves' });
    add('revision', { d: '2026-10-01', nm: 'ТЕСТ Мясо', u: 'кг', book: 5, fact: 5 });
    add('revision', { d: '2026-10-31', nm: 'ТЕСТ Мясо', u: 'кг', book: 8, fact: 7 });
    add('sales', { d: '2026-10-10', nm: 'ТЕСТ Рагу', q: 100, s: 30000 });
    add('writeoff', { d: '2026-10-12', nm: 'ТЕСТ Мясо', u: 'кг', q: 1, reason: 'порча', k: 'w' });
    add('writeoff', { d: '2026-10-13', nm: 'ТЕСТ Мясо', u: 'кг', q: 0.5, reason: 'питание персонала', k: 'i' });
    add('writeoff', { d: '2026-10-14', nm: 'ТЕСТ Рагу', u: 'шт', q: 2, reason: 'брак', k: 'w' });
    const strip = r => JSON.parse(JSON.stringify(r));
    const a = strip(F.calc(O, FROM, TO));
    // перестановка порядка операций в хранилище
    Object.keys(S.fc.ops).forEach(t => { const o = S.fc.ops[t], ks = Object.keys(o).reverse(), m = {}; ks.forEach(k => m[k] = o[k]); S.fc.ops[t] = m; });
    const b = strip(F.calc(O, FROM, TO));
    return { a, same: JSON.stringify(a) === JSON.stringify(b) };
  });
  const A = res.a, M = A.ings.tMeat, C = A.ings.tCarr, near = (x, y, m) => assert.ok(Math.abs(x - y) < 1e-6, m + ': ' + x + ' ≠ ' + y);
  assert.ok(res.same, 'порядок строк не влияет на результат');
  near(M.th.kg, 12, 'теор. мясо'); near(C.th.kg, 8, 'теор. морковь');
  near(M.book, 17, 'учётный расход мяса'); assert.strictEqual(M.mv.verified, true, 'баланс мяса сходится');
  near(M.actual, 18, 'фактический расход мяса = 5 + 20 − 7');
  near(M.dwo, 0.24, 'мясо в списанных блюдах'); near(M.wo.kg, 1, 'списание'); near(M.it.kg, 0.5, 'внутреннее');
  near(M.unexpl, 18 - 13.74, 'необъяснённое мяса'); near(M.unexplRub, 4.26 * 420, 'необъяснённое ₽ по цене закупки 420');
  near(M.rv.short, 1, 'недостача'); near(M.shortRub, 420, 'недостача ₽'); assert.ok(!M.rv.over, 'излишков нет');
  assert.strictEqual(C.actual, null, 'нет ревизии → факт не определён, не 0'); assert.strictEqual(C.unexpl, null, 'необъяснённое не определено');
  near(C.unexplBook, 9 - 8.16, 'учётное необъяснённое моркови');
  near(M.qtyEff, 2400, 'эффект количества'); near(M.priceEff, 360, 'эффект цены'); near(M.totEff, 2760, 'сумма'); near(M.qtyEff + M.priceEff, M.totEff, 'тождество количество+цена');
  const mt = id => A.metrics.filter(m => m.id === id)[0];
  near(mt('th').value, 12 * 420 + 8 * 45, 'теор. ₽'); near(mt('rev').value, 30000, 'выручка'); near(mt('fcRec').value, 5400 / 300, 'доля сырья по рецептуре %');
  assert.strictEqual(mt('act').value, 18 * 420, 'факт ₽ только по мясу (морковь не определена и не заменена 0)');
  assert.strictEqual(mt('fcAct').value, null, 'фактический фудкост не считается по части позиций'); assert.ok(/Не рассчитан|определён не по всем/.test(mt('fcAct').note + A.limits.join(' ')), 'причина названа');
  assert.ok(/Частично: по 1 из 2/.test(mt('act').note), 'частичный факт помечен');
  assert.ok(mt('act').formula && mt('act').src.length, 'у показателя есть формула и строки-источники');
  assert.strictEqual(A.exact, false); assert.ok(A.exactWhy.some(x => /НДС/.test(x)) && A.exactWhy.some(x => /неподтверждённ/.test(x)), 'ограничения названы: ' + A.exactWhy.join('; '));
  assert.ok(Object.keys(A.unmatched).length === 1, 'неизвестная позиция вне расчёта');
  assert.ok(!A.ings.undefined && Object.keys(A.ings).length === 2, 'в сырье только сопоставленное');
  assert.ok(M.rec.kg === 20 && C.rec.kg === 10, 'поступления не задвоены');
  assert.deepStrictEqual(errs, []);
  console.log('OK fc2'); await browser.close();
})().catch(e => { console.error('FAIL', e.message); process.exit(1); });
